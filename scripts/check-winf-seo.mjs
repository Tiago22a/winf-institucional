/* Auditoria SEO WINF Select™ e catálogo (CI após gerar capas). */
import {readFileSync,existsSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
import sharp from 'sharp';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>readFileSync(resolve(root,p),'utf8');
const cfg=JSON.parse(read('config/winf-active-cities.json'));
const siteMap=read('sitemap.xml');
const uniqueTitles=new Set(),uniqueDescriptions=new Set(),uniqueImages=new Set();
const metaOgForCity=html=>html.match(/<meta property="og:image" content="([^"]*)"/)?.[1];
for(const city of cfg.cities){
 const page=read(city.slug+'/index.html');
 const canonical='https://winf.com.br/'+city.slug+'/';
 const imageBase='https://winf.com.br/images/og/winf-select-'+city.origin+'-1200x630';
 const image=metaOgForCity(page) || imageBase+'.jpg';
 assert.ok([imageBase+'.jpg',imageBase+'-r2.jpg'].includes(image),'Imagem OG com nome territorial conhecido: '+city.city);
 const meta=(field,key)=>page.match(new RegExp('<meta '+field+'="'+key.replace(/\./g,'\\.')+'" content="([^"]*)"'))?.[1];
 const title=page.match(/<title>(.*?)<\/title>/)?.[1]||'';
 const description=meta('name','description');
 assert.ok(title.includes(city.city),'Title local: '+city.city);
 assert.ok(description?.includes(city.city),'Description local: '+city.city);
 assert.ok(!uniqueTitles.has(title),'Título duplicado: '+city.city);
 assert.ok(!uniqueDescriptions.has(description),'Description duplicada: '+city.city);
 uniqueTitles.add(title);uniqueDescriptions.add(description);
 assert.equal((page.match(/<title>/g)||[]).length,1);
 assert.equal(meta('property','og:url'),canonical);
 assert.equal(meta('property','og:image'),image);
 assert.equal(meta('name','twitter:image'),image);
 assert.equal(meta('property','og:image:width'),'1200');
 assert.equal(meta('property','og:image:height'),'630');
 assert.equal(meta('property','og:image:type'),'image/jpeg');
 assert.equal(meta('name','geo.region'),'BR-'+city.uf);
 assert.equal((page.match(/name="geo.region"/g)||[]).length,1);
 assert.equal((page.match(/name="geo.placename"/g)||[]).length,1);
 assert.ok(page.includes('<link rel="canonical" href="'+canonical+'"'),'canonical');
 assert.ok(page.includes('07H ÀS 22H'),'horário');
 assert.ok(page.includes('data-whatsapp="'+city.phone+'"'),'WhatsApp');
 assert.ok(siteMap.includes('<loc>'+canonical+'</loc>'),'sitemap');
 assert.ok(!page.includes('"@type":"LocalBusiness"'),'Não inventar lojas físicas');
 const json=JSON.parse(page.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/)?.[1]||'{}');
 const local=json['@graph']?.find(n=>n['@id']===canonical+'#organizacao');
 const service=json['@graph']?.find(n=>n['@type']==='Service');
 assert.equal(service?.areaServed?.name,city.city);
 assert.equal(local?.contactPoint?.hoursAvailable?.opens,'07:00');
 assert.equal(local?.contactPoint?.hoursAvailable?.closes,'22:00');
 assert.equal(local?.contactPoint?.telephone,city.phone==='5515997909049'?'+55-15-99790-9049':'+55-13-98111-3001');
 if(city.instagram)assert.ok(local.sameAs.includes('https://www.instagram.com/'+city.instagram+'/'),'Instagram local');
 for(const m of page.matchAll(/<img\b[^>]*>/g))assert.ok(/\balt\s*=/.test(m[0]),'Imagem sem alt '+city.city);
 assert.ok(!uniqueImages.has(image),'Imagem OG duplicada');uniqueImages.add(image);
 const file=image.replace('https://winf.com.br/','');
 assert.ok(existsSync(resolve(root,file)),'Imagem ausente '+file);
 const metadata=await sharp(resolve(root,file)).metadata();
 assert.equal(metadata.width,1200);assert.equal(metadata.height,630);assert.equal(metadata.format,'jpeg');
 console.log('✓ WINF Select SEO',city.city,city.uf);
}
const catalog=read('catalogo/index.html');
const catalogBase='https://winf.com.br/images/og/winf-catalogo-1200x630';
const catalogOg=catalog.match(/<meta property="og:image" content="([^"]*)"/)?.[1];
assert.ok([catalogBase+'.jpg',catalogBase+'-r2.jpg'].includes(catalogOg),'Imagem social catalogo no dominio oficial');
assert.ok(catalog.includes('<meta name="twitter:image" content="'+catalogOg+'"'),'Twitter deve usar capa social idêntica');
assert.ok(siteMap.includes('<image:loc>'+catalogOg+'</image:loc>'),'Sitemap deve usar a mesma imagem social do catalogo');
const catalogFile=catalogOg.replace('https://winf.com.br/','');
assert.ok(existsSync(resolve(root,catalogFile)),'Imagem social do catálogo inexistente');
const catalogImage=await sharp(resolve(root,catalogFile)).metadata();
assert.equal(catalogImage.width,1200);assert.equal(catalogImage.height,630);assert.equal(catalogImage.format,'jpeg');
console.log('✓ OG catálogo WINF, imagem JPEG 1200x630');
console.log('✓ '+cfg.cities.length+' cidades com SEO distinto + '+(cfg.cities.length+1)+' capas sociais disponíveis.');
